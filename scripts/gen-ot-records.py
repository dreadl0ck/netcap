"""Generate AuditRecord adapters for the industrial protocol messages."""
import json
import re
import subprocess
from pathlib import Path

types = Path(__file__).resolve().parents[1] / 'types'
schema = (types / 'netcap.proto').read_text()
out = '''// Code generated by scripts/gen-ot-records.py; DO NOT EDIT.
package types
import (
    "encoding/json"
    "fmt"
    "time"

    "github.com/prometheus/client_golang/prometheus"

    "github.com/dreadl0ck/netcap/internal/encoder"
)
var otEncoder = encoder.NewValueEncoder()
func otJSONField(v any) string {
    b, err := json.Marshal(v)
    if err != nil { return "" }
    return string(b)
}
'''

def csv_expr(repeated, field_type, name):
    if name == 'Timestamp':
        return 'formatTimestamp(r.Timestamp)'
    if repeated or field_type[0].isupper():
        return f'otJSONField(r.{name})'
    if field_type == 'string':
        return f'r.{name}'
    return f'fmt.Sprint(r.{name})'


for name in 'PTPv2 GOOSE SampledValues EtherCAT OPCUAPubSub IEC104 MMS AMS'.split():
    body = re.search(r'message '+name+r' \{([^}]+)', schema)[1]
    fields = re.findall(r'^\s*(repeated\s+)?(\w+)\s+(\w+) = \d+;', body, re.MULTILINE)
    cols = ', '.join(json.dumps(field) for _, _, field in fields)
    vals = ', '.join(csv_expr(*field) for field in fields)
    out += f'''
var metric{name} = prometheus.NewCounter(prometheus.CounterOpts{{Name:"nc_{name.lower()}", Help:"Decoded {name} records"}})
func (r *{name}) Time() int64 {{return r.Timestamp}}
func (r *{name}) Src() string {{if ip:=r.Context.GetSrcIP(); ip!="" {{return ip}};return r.Context.GetSrcMAC()}}
func (r *{name}) Dst() string {{if ip:=r.Context.GetDstIP(); ip!="" {{return ip}};return r.Context.GetDstMAC()}}
func (r *{name}) SetPacketContext(c *PacketContext) {{if c != nil {{v:=*c; r.Context=&v}}}}
func (*{name}) Analyze() {{}}
func (*{name}) NetcapType() Type {{return Type_NC_{name}}}
func (*{name}) Inc() {{metric{name}.Inc()}}
func (r *{name}) JSON() (string,error) {{v:=*r; v.Timestamp/=int64(time.Millisecond);return jsonMarshaler.MarshalToString(&v)}}
func (*{name}) CSVHeader() []string {{return filter([]string{{{cols}}})}}
func (r *{name}) CSVRecord() []string {{return filter([]string{{{vals}}})}}
func (r *{name}) Encode() []string {{v:=r.CSVRecord();for i,k:=range r.CSVHeader() {{if k=="Timestamp" {{v[i]=otEncoder.Int64(k,r.Timestamp)}} else {{v[i]=otEncoder.String(k,v[i])}}}};return v}}
'''
(types / 'industrial_generated.go').write_bytes(subprocess.check_output(['gofmt'], input=out.encode()))
