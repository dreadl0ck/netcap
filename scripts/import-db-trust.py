#!/usr/bin/env python3
"""Import a reviewed community registry using an independently supplied SHA-256."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("registry", type=Path)
parser.add_argument("sha256")
args = parser.parse_args()
body = args.registry.read_bytes()
if hashlib.sha256(body).hexdigest() != args.sha256:
    parser.error("registry SHA-256 mismatch")
records = json.loads(body)
if not records or any(r.get("decision") != "approved-for-publication" for r in records):
    parser.error("registry must contain explicit publication reviews")
out = Path(__file__).resolve().parents[1] / "internal/dbs/community_registry_generated.go"
out.write_text(
    "// Code generated by scripts/import-db-trust.py; DO NOT EDIT.\n\n"
    "package dbs\n\n"
    "const communityRegistrySHA256 = " + json.dumps(args.sha256) + "\n\n"
    "const communityRegistry = " + json.dumps(body.decode()) + "\n"
)
print(out)
